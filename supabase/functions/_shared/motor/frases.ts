/** Frases do momento do dia ("HH:MM"), somadas às gerais. */
export function frasesDoHorario(hora: string): string[] {
  const h = Number(hora.slice(0, 2));
  const momento = h < 12 ? FRASES_MANHA : h < 18 ? FRASES_TARDE : FRASES_NOITE;
  return [...momento, ...FRASES_GERAIS];
}
